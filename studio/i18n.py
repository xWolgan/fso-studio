def t(lang: str) -> dict:
    lang = lang if lang in JEZYKI else "pl"
    out = dict(T["pl"])
    if lang != "pl":
        out.update(T["en"])
        out.update(T[lang])
    from .config import CFG                       # nazwa_studia w config.yaml zastępuje tytuł warsztatów
    n = CFG.get("nazwa_studia")
    if n:
        out["tytul"] = L(n, lang) if isinstance(n, dict) else str(n)
    return out


def K(klucz: str, **kw) -> str:
    """Komunikat do przetłumaczenia przy wyświetleniu (w bazie, w HTTPException): „@klucz|{json}”."""
    import json
    return "@" + klucz + ("|" + json.dumps(kw, ensure_ascii=False) if kw else "")


def przetlumacz(tekst, lang: str):
    """„@klucz|{…}” → tekst w języku lang; inne teksty bez zmian."""
    if not isinstance(tekst, str) or not tekst.startswith("@"):
        return tekst
    import json
    klucz, _, js = tekst[1:].partition("|")
    wzor = t(lang).get(klucz)
    if wzor is None:
        return tekst
    try:
        kw = json.loads(js) if js else {}
        return wzor.format(**kw)
    except Exception:
        return wzor


def L(d, lang: str, domyslnie: str = "") -> str:
    """Tekst z wielojęzycznego słownika {pl, en, fr} (z YAML); zwykły tekst przechodzi bez zmian."""
    if not isinstance(d, dict):
        return d if d is not None else domyslnie
    return d.get(lang) or (d.get("en") if lang != "pl" else None) or d.get("pl") or d.get("en") or domyslnie
